import uuid
from datetime import datetime

from sqlalchemy import DateTime, MetaData, Uuid, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# Deterministic constraint names. Without a convention Postgres invents its own
# ("owners_phone_key", "pgs_check1"), and code that has to tell one violated
# constraint from another — duplicate phone vs duplicate email on signup — has
# nothing stable to match on. Set before the first table exists so no later
# migration ever has to rename anything.
NAMING_CONVENTION = {
    "pk": "pk_%(table_name)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "ix": "ix_%(table_name)s_%(column_0_name)s",
}


class Base(DeclarativeBase):
    """Declarative base for all ORM models.

    Every model inherits from this. Alembic's ``target_metadata`` points at
    ``Base.metadata`` so migrations can be autogenerated as models are added.
    """

    metadata = MetaData(naming_convention=NAMING_CONVENTION)


class UUIDPrimaryKey:
    """Mixin: ``id`` UUID primary key generated in Python.

    CLAUDE.md §7 — never a DB function like ``uuidv7()``, so the schema stays
    portable across Postgres versions and hosts.
    """

    id: Mapped[uuid.UUID] = mapped_column(Uuid(as_uuid=True), primary_key=True, default=uuid.uuid4)


class Timestamps:
    """Mixin: ``created_at`` / ``updated_at``, both timezone-aware."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )
